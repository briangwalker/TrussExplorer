// ===== Export a design as the professor's TrussFEA_Bridge_SE310.py with Section 1 filled in =====
(function (root) {
'use strict';
const TYPE_LABEL = { top: 'Top chord', bot: 'Bot-chord', end: 'End post', vert: 'Vertical', diag: 'Diagonal', brace: 'Edge brace', claw: 'Claw hook' };

function f3(v) { const s = (Math.round(v * 1000) / 1000).toFixed(3); return s === '-0.000' ? '0.000' : s; }
function pad(s, n) { s = String(s); return s.length >= n ? s : ' '.repeat(n - s.length) + s; }

function describe(d, tr) {
  const fam = d.family === 'warren' ? 'Warren (no verticals)' : 'panel-grid truss';
  const parts = [`${d.panels}-panel ${fam}`, `height ${f1(d.height)} mm`, `overall length ${f1(tr.overall)} mm`,
    `${f1(tr.bookSpan[1] - tr.bookSpan[0])} mm books on the ${d.deck === 'bottom' ? 'BOTTOM' : 'TOP'} chord`];
  if (Math.abs((d.ratio || 1) - 1) > 1e-6) parts.push(`centre/end panel width ratio ${(+d.ratio).toFixed(2)}`);
  if (tr.info.curve) parts.push(`${tr.info.shape} bottom chord ${f1(Math.abs(tr.info.curve))} mm ${tr.info.curve < 0 ? 'below the deck (sag)' : 'above the desk (arch)'}`);
  if (tr.info.deskEnds && tr.info.deskEnds !== 'truss') parts.push(tr.info.deskEnds === 'feet' ? 'desk panels are bottom-chord feet only' : 'no end posts on the desk panels');
  if (tr.info.a) parts.push(`${tr.info.a} desk panel${tr.info.a > 1 ? 's' : ''} of ${f1(tr.info.deskWidth)} mm per side`);
  if (d.family !== 'warren' && tr.info.sideAngleActual < 89.99)
    parts.push(`end posts at ${tr.info.sideAngleActual.toFixed(1)} deg leaning ${d.sideLean === 'out' ? 'OUT' : 'IN'}`);
  return parts.join(', ');
}
function f1(v) { return (Math.round(v * 10) / 10).toString(); }

function diagCodeText(c) { return { P: 'down toward mid-span (Pratt)', H: 'up toward mid-span (Howe)', X: 'X (both)', N: 'none' }[c]; }

function section1(name, d, tr, res, load, opts) {
  const L = [];
  const nTop = tr.keys.filter(k => k[0] === 'T').length;
  L.push('# =============================================================================');
  L.push('#  1. PROBLEM DEFINITION   <-- THIS IS THE ONLY BLOCK YOU NEED TO CHANGE');
  L.push('# =============================================================================');
  L.push(`#  DESIGN : ${name}`);
  L.push(`#  ${describe(d, tr)}.`);
  L.push('#  Generated by the SE 310 Truss Explorer page; everything outside this block');
  L.push('#  (and the plot title / axis limits) is the original course script.');
  if (d.family !== 'warren' && tr.info.diag) {
    const half = Math.ceil(tr.info.M / 2), a = tr.info.a;
    L.push('#  Diagonals, panel by panel (left half; right half is the mirror image):');
    for (let i = 0; i < half; i++) L.push(`#     ${i < a ? 'desk panel ' + (i + 1) : 'span panel ' + (i + 1 - a)}: ${diagCodeText(tr.info.diag[i])}`);
  }
  L.push('#  Panel widths (mm, left to right): ' + tr.widths.map(f1).join(', '));
  L.push('#');
  L.push(`D_truss = ${f3(d.height)}          # mm - truss height above the desk top ( <= 100 mm )`);
  L.push(`L_panel = ${f3(tr.spanWidths[0])}          # mm - end panel length inside the span (panels may vary, see list above)`);
  L.push(`SPAN    = ${f3(d.span || 200)}         # mm - clear span between the desk edges`);
  L.push(`OVERALL = ${f3(tr.overall)}         # mm - overall length of the truss (200 - 300 mm)`);
  L.push(`x_sup_L = ${f3(tr.nodes[(res.activeSupports.find(q => q.pin) || res.activeSupports[0]).node][0])}         # mm - pinned support (on the left desk)`);
  L.push(`x_sup_R = ${f3((d.span || 200) - tr.nodes[(res.activeSupports.find(q => q.pin) || res.activeSupports[0]).node][0])}         # mm - matching roller on the right desk`);
  L.push('');
  L.push('# ---- Nodal coordinates [x, y] (node numbering starts at 0, as in the original)');
  L.push('nodeCords = np.array([');
  tr.nodes.forEach((n, i) => {
    let note = tr.keys[i];
    if (i === tr.pin) note += ' - LEFT SUPPORT  (pin)';
    if (i === tr.roller) note += ' - RIGHT SUPPORT (roller)';
    if (i === res.midNode) note += ' - mid-span deck joint';
    L.push(`    [${pad(f3(n[0]), 9)}, ${pad(f3(n[1]), 8)}],   # ${pad(i, 2)}  ${note}`);
  });
  L.push('])');
  L.push('');
  L.push('# ---- Element connectivity [near node, far node]');
  L.push('elemNodes = np.array([');
  let cur = null, row = [];
  const flush = () => { if (row.length) L.push('    ' + row.join(', ') + ','); row = []; };
  tr.elems.forEach(e => {
    if (e.type !== cur) {
      flush(); cur = e.type;
      L.push(`    # --- ${TYPE_LABEL[e.type]}${(d.deck === 'bottom' ? e.type === 'bot' : e.type === 'top') ? ' (the deck the books sit on)' : ''}`);
    }
    row.push(`[${e.i}, ${e.j}]`);
    if (row.length === 6) flush();
  });
  flush();
  L.push('])');
  L.push('');
  L.push('# ---- Member labels (for readable output tables only)');
  const groups = [];
  tr.elems.forEach(e => { const lab = TYPE_LABEL[e.type]; if (groups.length && groups[groups.length - 1][0] === lab) groups[groups.length - 1][1]++; else groups.push([lab, 1]); });
  L.push('elemLabel = (' + groups.map(([l, n]) => `["${l}"]*${n}`).join(' + ') + ')');
  L.push('');
  L.push('# ---- Material and section of every element');
  L.push('modE = np.full((elemNodes.shape[0], 1), E_balsa)    # MPa');
  if (tr.elems.every(e => (e.n || 1) === 1)) {
    L.push('Area = np.full((elemNodes.shape[0], 1), A_stick)    # mm^2');
    L.push('Imom = np.full((elemNodes.shape[0], 1), I_stick)    # mm^4');
  } else {
    const iMul = e => e.n === 1 ? 1 : (e.bundle === 'compact' && e.n === 4 ? 16 : e.n);
    L.push('#  Some members are doubled up: n sticks glued together. Area = n x A_stick.');
    L.push('#  Imom: n x I_stick for sticks glued in a row; 16 x I_stick for a 2x2 bundle.');
    L.push('Area = np.array([' + tr.elems.map((e, k) => `[${e.n}*A_stick]`).join(', ') + '])    # mm^2, one row per element');
    L.push('Imom = np.array([' + tr.elems.map(e => `[${iMul(e)}*I_stick]`).join(', ') + '])    # mm^4, one row per element');
    const extra = tr.elems.reduce((acc, e) => acc + (e.n - 1) * Math.hypot(tr.nodes[e.j][0] - tr.nodes[e.i][0], tr.nodes[e.j][1] - tr.nodes[e.i][1]), 0);
    L.push(`#  NOTE: the course script's mass line (below Section 1) counts ONE stick per member.`);
    L.push(`#  The doubled members add ${f1(extra)} mm of stick per truss, so add ${f1(extra)} x N_TRUSS x A_stick x rho to its M.`);
  }
  L.push('');
  L.push('# ---- Displacement constraints [node, dof, value]   dof: 1 = x , 2 = y');
  L.push('DispCon = np.array([');
  res.DispCon.forEach(([n, dof]) => {
    const sp = res.activeSupports.find(q => q.node === n);
    L.push(`    [${n}, ${dof}, 0.0],      # node ${n} (x = ${f1(tr.nodes[n][0])} mm) : ${sp && sp.pin ? 'pinned ' : 'roller '} -> ${dof === 1 ? 'ux' : 'uy'} = 0`);
  });
  L.push('])');
  if (res.activeSupports.some(q => q.brace)) L.push('#  NOTE: the inside-edge braces also have a friction spring (' + res.kf + ' N/mm, vertical) in the Explorer. The course script has no springs, so its brace results will differ slightly.');
  if (res.activeSupports.some(q => q.claw)) L.push('#  NOTE: claw nodes are listed as fixed supports. In the Explorer a claw can only pull down; check that its vertical reaction comes out negative.');
  (res.lifted || []).forEach(q => L.push(`#  Support at node ${q.node} (x = ${f1(q.x)} mm) was dropped: it would have to pull the bridge down, so that end lifts off the table.`));
  L.push('');
  L.push('# ---- Applied forces [node, dof, value]   (downward = negative y)');
  if (d.loads && d.loads.length) {
    L.push('#  Custom loads from the Explorer (weights are shares of the total book mass; each share is put on the deck joints):');
    d.loads.forEach(Ld => L.push(`#     ${Ld.type}: ${Ld.type === 'point' ? 'at x = ' + f1(+Ld.x) + ' mm' : 'x = ' + f1(+Ld.a) + ' to ' + f1(+Ld.b) + ' mm'}, weight ${(+Ld.w).toFixed(2)}`));
    L.push('#  Each deck joint below takes its share of the total (point loads split by the lever rule).');
  } else {
    L.push(`#  The books are a uniform load over their ${f1(tr.bookSpan[1] - tr.bookSpan[0])} mm length, centred on mid-span`);
    L.push(`#  (x = ${f1(tr.bookSpan[0])} to ${f1(tr.bookSpan[1])} mm). Each deck joint takes the part of the book lying`);
    L.push('#  between the midpoints to its neighbouring deck joints (tributary length).');
  }
  L.push('Fval = np.array([');
  tr.trib.forEach(t => L.push(`    [${t.node}, 2, -P_truss * ${t.frac.toFixed(6)}],`));
  L.push('])');
  L.push('');
  L.push('');
  L.push(`CSV_OUT     = '${name.replace(/[^A-Za-z0-9_-]+/g, '_')}_results.csv'   # where the table is written`);
  L.push(`DEFL_LIMIT  = ${f3(opts.deflLimit)}      # mm - allowable mid-span deflection (design constraint)`);
  L.push(`MID_NODE    = ${res.midNode}        # mid-span deck joint whose deflection is checked`);
  L.push('SCALE_PLOT  = 20       # deformation magnification for the plot');
  return L.join('\n');
}

// Names in exports: one line, and only characters that are safe in a Python comment, string or f-string, and a CSV cell.
function pyName(s) {
  const t = String(s == null ? '' : s).replace(/[\u0000-\u001F\u007F\u2028\u2029]+/g, ' ').replace(/[^\p{L}\p{N} _.,:;()+#·\-\/]/gu, '').replace(/\s+/g, ' ').trim().slice(0, 80);
  return t || 'Design';
}
function exportPy(template, name, d, tr, res, mat, load, opts) {
  const safeName = pyName(name);
  const matTxt = [
    `b_stick   = ${mat.b}          # mm   - stick width  (1/8 inch)`,
    `h_stick   = ${mat.h}          # mm   - stick depth  (1/8 inch)`,
    `E_balsa   = ${(+mat.E).toFixed(1)}        # MPa  - Young's modulus along the grain`,
    `sig_t_ult = ${mat.sigT}           # MPa  - ultimate TENSILE  strength along the grain`,
    `sig_c_ult = ${mat.sigC}           # MPa  - ultimate CRUSHING strength along the grain`,
    `rho_balsa = ${(mat.rho * 1e9).toFixed(0)}e-9        # kg/mm^3 - density (${(mat.rho * 1e9).toFixed(0)} kg/m^3)`,
    `FS_req    = ${(+mat.FS).toFixed(1)}           # [-]  - required factor of safety (project constraint)`,
    `K_eff     = ${(+mat.K).toFixed(1)}           # [-]  - effective length factor, pin-pin ends`,
  ].join('\n');
  const books = [
    `m_book_SA  = ${(+load.mBook1).toFixed(2)}         # kg - "Structural Analysis"`,
    `m_book_MM  = ${(+load.mBook2).toFixed(2)}         # kg - "Machines and Mechanisms"`,
  ].join('\n');
  const ntruss = `N_TRUSS    = ${load.nTruss}                                  # identical vertical side trusses`;
  const xs = tr.nodes.map(n => n[0]);
  const lim = `ax.set_xlim(${Math.floor(Math.min(...xs) - 25)}, ${Math.ceil(Math.max(...xs) + 25)}); ax.set_ylim(${Math.floor(Math.min(-30, tr.minY - 20))}, ${Math.ceil(Math.max(tr.maxY, 0) + 30)})`;
  const title = `ax.set_title(f"${safeName}  "`;
  return template
    .replace('{{MAT}}', matTxt)
    .replace('{{BOOKS}}', books)
    .replace('{{NTRUSS}}', ntruss)
    .replace('{{SECTION1}}', section1(safeName, d, tr, res, load, opts))
    .replace('{{TITLE}}', title)
    .replace('{{LIMITS}}', lim);
}

const api = { exportPy, describe, TYPE_LABEL, pyName };
if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.TrussExport = api;
})(typeof window !== 'undefined' ? window : globalThis);
