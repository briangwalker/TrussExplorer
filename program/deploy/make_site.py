# The website's files for one release (#3): program/site/index.html (the build, unchanged) and program/site/.htaccess,
# whose Content-Security-Policy is read from THIS build's index.csp.txt (#297), so the script hashes always match.
# Nothing else is published: no src, tests or .git. Run after build.py:  python3 deploy/make_site.py
import os, sys
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
site = os.path.join(here, 'site')
def read(name):
    p = os.path.join(here, name)
    if not os.path.exists(p): sys.exit(f'make_site.py: {name} is missing; run build.py first')
    return open(p, encoding='utf-8').read()
page = read('index.html')
policy = [l for l in read('index.csp.txt').splitlines() if l.strip() and not l.startswith('#')]
if len(policy) != 1 or "script-src 'sha256-" not in policy[0] or 'unsafe-inline' in policy[0].split('; style-src')[0]:
    sys.exit('make_site.py: index.csp.txt must hold one policy line with script hashes and no unsafe-inline scripts')
if '"' in policy[0]: sys.exit('make_site.py: the policy must not contain a double quote')
# Apache on IONOS: https only, no folder listing, the security headers (White Hat WH-W; website guide Part 5).
# HSTS starts at one day and goes up only once https works everywhere. text/html is sent with its charset (#77).
htaccess = f'''# Generated by program/deploy/make_site.py for this release; don't edit on the server.
Options -Indexes
DirectoryIndex index.html
AddDefaultCharset utf-8
RewriteEngine On
RewriteCond %{{HTTPS}} !=on
RewriteRule ^ https://%{{HTTP_HOST}}%{{REQUEST_URI}} [L,R=301]
<IfModule mod_headers.c>
  Header always set Content-Security-Policy "{policy[0]}"
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
  Header always set Strict-Transport-Security "max-age=86400"
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
'''
os.makedirs(site, exist_ok=True)
for f in os.listdir(site): os.remove(os.path.join(site, f))
open(os.path.join(site, 'index.html'), 'w', encoding='utf-8').write(page)
open(os.path.join(site, '.htaccess'), 'w', encoding='utf-8').write(htaccess)
print('site/: index.html (%d bytes), .htaccess' % len(page.encode('utf-8')))
