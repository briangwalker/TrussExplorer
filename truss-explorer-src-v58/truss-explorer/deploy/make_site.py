# The website's files for one main (v6x) release (#3, plan c): site/index.html (the committed build, unchanged) and
# site/.htaccess with a Content-Security-Policy that allows exactly this page's inline scripts by hash (WH-N3, #297's
# rule, computed here because main's build.py doesn't write index.csp.txt). Nothing else is published.
import os, re, sys, hashlib, base64
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
site = os.path.join(here, 'site')
page = open(os.path.join(here, 'index.html'), encoding='utf-8').read()
if re.search(r'<script[^>]+src=', page): sys.exit('make_site.py: a <script src=...> would need its own CSP entry')
if re.search(r'\son[a-z]+\s*=\s*["\']', page): sys.exit('make_site.py: an inline on...= handler would be blocked by the hash-only policy')
hashes = [base64.b64encode(hashlib.sha256(m.group(1).encode('utf-8')).digest()).decode('ascii') for m in re.finditer(r'<script>(.*?)</script>', page, re.S)]
if not hashes: sys.exit('make_site.py: no inline scripts found')
policy = ("default-src 'self'; script-src " + ' '.join(f"'sha256-{h}'" for h in hashes) +
          "; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; font-src 'self' data:; connect-src 'self';"
          " worker-src 'self' blob:; object-src 'none'; base-uri 'none'; frame-ancestors 'self'; form-action 'none'")
htaccess = f'''# Generated by deploy/make_site.py for this release; don't edit on the server.
Options -Indexes
DirectoryIndex index.html
AddDefaultCharset utf-8
RewriteEngine On
RewriteCond %{{HTTPS}} !=on
RewriteRule ^ https://%{{HTTP_HOST}}%{{REQUEST_URI}} [L,R=301]
<IfModule mod_headers.c>
  Header always set Content-Security-Policy "{policy}"
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
  Header always set Strict-Transport-Security "max-age=86400"
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
'''
os.makedirs(site, exist_ok=True)
for f in os.listdir(site): os.remove(os.path.join(site, f))
open(os.path.join(site, 'index.html'), 'w', encoding='utf-8').write(page)
open(os.path.join(site, '.htaccess'), 'w', encoding='utf-8').write(htaccess)
open(os.path.join(site, 'policy.txt'), 'w', encoding='utf-8').write(policy + '\n')
print('site/: index.html (%d bytes), .htaccess, %d script hashes' % (len(page.encode('utf-8')), len(hashes)))
